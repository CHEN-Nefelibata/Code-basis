#字典及其基本操作
mydict={
    "A":{"部门":"科技部","工资":3000,"级别":1},
    "B":{"部门":"市场部","工资":5000,"级别":2},
    "C":{"部门":"市场部","工资":7000,"级别":3},
    "D":{"部门":"科技部","工资":4000,"级别":1},
    "E":{"部门":"市场部","工资":6000,"级别":2}
}
print(mydict)

for name in mydict:
    if mydict[name]["级别"]==1:
        mydict[name]["级别"]=2
        mydict[name]["工资"]+=1000
print(mydict)