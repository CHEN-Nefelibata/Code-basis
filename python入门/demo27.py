#数据容器之元组
#元组中数据不能被修改，但内部嵌套的列表可以修改
t1=(1,"Hello",True)
t2=()
t3=tuple()#t2和t3都是空元组
print(f"t1的类型为{type(t1)}")#类型为tuple
t4=("hello",)#若元组只有一个数据，需在末尾加逗号
t5=((1,2,3),(4,5,6))
num=t5[1][2]
print(num)
#元组的查找index
index=t1.index(1)
print(index)
#元组的统计元素个数count
t6=(1,1,1,1,2,2,2,3,3,3)
count=t6.count(1)
print(count)
#统计元组内元素总数len
print(len(t6))